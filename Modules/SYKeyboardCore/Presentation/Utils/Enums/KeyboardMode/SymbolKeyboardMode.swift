import UIKit

public enum SymbolKeyboardMode: Equatable {
    case `default`
    case URL
    case emailAddress
    case webSearch
    
    /// 주소 자판(URL·이메일)의 2페이지. 기본 자판 2페이지와 같은 구성이되
    /// 1페이지와 겹치는 `_`, `|`, `~`, `$`를 `€`, `±`, `°`, `×`로 바꿨다
    private static let addressSecondPageKeyList: [[[String]]] = [
        [ ["€"], ["\\"], ["±"], ["°"], ["<"], [">"], ["×"], ["£"], ["¥"], ["•"] ],
        [ ["※"], ["☆"], ["★"], ["○"], ["●"], ["□"], ["■"], ["△"], ["▲"], ["♡"] ],
        [ ["."], [","], ["?"], ["!"], ["’"] ]
    ]

    public init(keyboardType: UIKeyboardType?) {
        switch keyboardType {
        case .URL:
            self = .URL
        case .emailAddress:
            self = .emailAddress
        case .webSearch:
            self = .webSearch
        default:
            self = .default
        }
    }
    
    /// 기호 자판 배열
    /// - Parameter usesNumberRow: 자판 위에 숫자 행이 있는지 여부.
    ///   숫자 행이 있으면 첫 줄 숫자가 중복되므로 기호로 채운다
    func keyList(usesNumberRow: Bool) -> [[[[String]]]] {
        switch self {
        case .default, .webSearch:
            guard usesNumberRow else {
                return [
                    [
                        [ ["1"], ["2"], ["3"], ["4"], ["5"], ["6"], ["7"], ["8"], ["9"], ["0"] ],
                        [ ["-"], ["/"], [":"], [";"], ["("], [")"], ["₩"], ["&"], ["@"], ["”"] ],
                        [ ["."], [","], ["?"], ["!"], ["’"] ]
                    ],
                    [
                        [ ["["], ["]"], ["{"], ["}"], ["#"], ["%"], ["^"], ["*"], ["+"], ["="] ],
                        [ ["_"], ["\\"], ["|"], ["~"], ["<"], [">"], ["$"], ["£"], ["¥"], ["•"] ],
                        [ ["."], [","], ["?"], ["!"], ["’"] ]
                    ]
                ]
            }
            // 숫자 밑에 있던 줄을 숫자 행 밑에 그대로 두고, 새 줄을 그 아래에 넣는다
            return [
                [
                    [ ["-"], ["/"], [":"], [";"], ["("], [")"], ["₩"], ["&"], ["@"], ["”"] ],
                    [ ["["], ["]"], ["{"], ["}"], ["#"], ["%"], ["^"], ["*"], ["+"], ["="] ],
                    [ ["."], [","], ["?"], ["!"], ["’"] ]
                ],
                [
                    [ ["_"], ["\\"], ["|"], ["~"], ["<"], [">"], ["$"], ["£"], ["¥"], ["•"] ],
                    [ ["※"], ["☆"], ["★"], ["○"], ["●"], ["□"], ["■"], ["△"], ["▲"], ["♡"] ],
                    [ ["."], [","], ["?"], ["!"], ["’"] ]
                ]
            ]
        case .URL:
            if usesNumberRow {
                // 1페이지에 있던 줄은 자리를 지키고 2페이지 내용이 그 아래로 내려온다.
                // 양쪽에 있던 `[`, `]` 중복은 하나로 줄인다
                let merged: [[[String]]] = [
                    [ ["@"], ["&"], ["%"], ["?"], [","], ["="], ["["], ["]"], [], [] ],
                    [ ["*"], ["$"], ["#"], ["!"], ["’"], ["^"], ["~"], [";"], ["("], [")"] ],
                    [ ["_"], [":"], ["-"], ["+"], [] ]
                ]
                return [merged, Self.addressSecondPageKeyList]
            }
            return [
                [
                    [ ["1"], ["2"], ["3"], ["4"], ["5"], ["6"], ["7"], ["8"], ["9"], ["0"] ],
                    [ ["@"], ["&"], ["%"], ["?"], [","], ["="], ["["], ["]"], [], [] ],
                    [ ["_"], [":"], ["-"], ["+"], [] ]
                ],
                [
                    [ ["1"], ["2"], ["3"], ["4"], ["5"], ["6"], ["7"], ["8"], ["9"], ["0"] ],
                    [ ["*"], ["$"], ["#"], ["!"], ["’"], ["^"], ["["], ["]"], [], [] ],
                    [ ["~"], [";"], ["("], [")"], [] ]
                ]
            ]
        case .emailAddress:
            if usesNumberRow {
                // 둘째 줄 양 끝에 두 번 있던 `’`는 하나로 줄인다
                let merged: [[[String]]] = [
                    [ ["$"], ["!"], ["~"], ["&"], ["="], ["#"], ["["], ["]"], [], [] ],
                    [ ["’"], ["|"], ["{"], ["}"], ["?"], ["%"], ["^"], ["*"], ["/"], [] ],
                    [ ["."], ["_"], ["-"], ["+"], [] ]
                ]
                return [merged, Self.addressSecondPageKeyList]
            }
            return [
                [
                    [ ["1"], ["2"], ["3"], ["4"], ["5"], ["6"], ["7"], ["8"], ["9"], ["0"] ],
                    [ ["$"], ["!"], ["~"], ["&"], ["="], ["#"], ["["], ["]"], [], [] ],
                    [ ["."], ["_"], ["-"], ["+"], [] ]
                ],
                [
                    [ ["’"], ["|"], ["{"], ["}"], ["?"], ["%"], ["^"], ["*"], ["/"], ["’"] ],
                    [ ["$"], ["!"], ["~"], ["&"], ["="], ["#"], ["["], ["]"], [], [] ],
                    [ ["."], ["_"], ["-"], ["+"], [] ]
                ]
            ]
        }
    }
}
