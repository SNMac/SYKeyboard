import UIKit

public enum SymbolKeyboardMode: Equatable {
    case `default`
    case URL
    case emailAddress
    case webSearch
    
    public init(keyboardType: UIKeyboardType?) {
        switch keyboardType {
        case .URL:
            self = .URL
        case .emailAddress:
            self = .emailAddress
        case .webSearch:
            self = .webSearch
        default:
            self = .default
        }
    }
    
    var keyList: [[[[String]]]] {
        switch self {
        case .default, .webSearch:
            return [
                [
                    [ ["1"], ["2"], ["3"], ["4"], ["5"], ["6"], ["7"], ["8"], ["9"], ["0"] ],
                    [ ["-"], ["/"], [":"], [";"], ["("], [")"], ["₩"], ["&"], ["@"], ["”"] ],
                    [ ["."], [","], ["?"], ["!"], ["’"] ]
                ],
                [
                    [ ["["], ["]"], ["{"], ["}"], ["#"], ["%"], ["^"], ["*"], ["+"], ["="] ],
                    [ ["_"], ["\\"], ["|"], ["~"], ["<"], [">"], ["$"], ["£"], ["¥"], ["•"] ],
                    [ ["."], [","], ["?"], ["!"], ["’"] ]
                ]
            ]
        case .URL:
            return [
                [
                    [ ["1"], ["2"], ["3"], ["4"], ["5"], ["6"], ["7"], ["8"], ["9"], ["0"] ],
                    [ ["@"], ["&"], ["%"], ["?"], [","], ["="], ["["], ["]"], [], [] ],
                    [ ["_"], [":"], ["-"], ["+"], [] ]
                ],
                [
                    [ ["1"], ["2"], ["3"], ["4"], ["5"], ["6"], ["7"], ["8"], ["9"], ["0"] ],
                    [ ["*"], ["$"], ["#"], ["!"], ["’"], ["^"], ["["], ["]"], [], [] ],
                    [ ["~"], [";"], ["("], [")"], [] ]
                ]
            ]
        case .emailAddress:
            return [
                [
                    [ ["1"], ["2"], ["3"], ["4"], ["5"], ["6"], ["7"], ["8"], ["9"], ["0"] ],
                    [ ["$"], ["!"], ["~"], ["&"], ["="], ["#"], ["["], ["]"], [], [] ],
                    [ ["."], ["_"], ["-"], ["+"], [] ]
                ],
                [
                    [ ["’"], ["|"], ["{"], ["}"], ["?"], ["%"], ["^"], ["*"], ["/"], ["’"] ],
                    [ ["$"], ["!"], ["~"], ["&"], ["="], ["#"], ["["], ["]"], [], [] ],
                    [ ["."], ["_"], ["-"], ["+"], [] ]
                ]
            ]
        }
    }
}
